import { useState, type ReactNode } from 'react'
import { useMutation, useQuery } from '@tanstack/react-query'
import { createEvalJob, createRedTeamJob, getEvalJob, getRedTeamJob } from '@/api/client'
import { isApiError } from '@/api/errors'
import type { EvalJob, RedTeamJob } from '@/api/types'
import { RequestError } from '@/components/console/RequestError'
import { SigSays } from '@/components/sig'
import { Card, CardLabel, InkButton } from '@/components/ui'
import { cn } from '@/lib/cn'
import { errorTypeRows, jobDone, proofKpis, redteamMarks, type MarkTone } from '@/lib/proof'
import { useProofStore } from '@/state/proofStore'

const POLL_MS = 2_000

function useJob<T extends { status: string }>(key: string, id: string | null, get: (id: string) => Promise<T>) {
  return useQuery({
    queryKey: [key, id],
    queryFn: () => get(id!),
    enabled: Boolean(id),
    retry: false,
    // Poll until the job finishes (contract: every 2 s).
    refetchInterval: (q) => (jobDone(q.state.data) ? false : POLL_MS),
  })
}

function Tile({ label, testId, children, bad }: { label: string; testId: string; children: ReactNode; bad?: boolean }) {
  return (
    <Card className="p-4">
      <div className="text-meta text-muted">{label}</div>
      <div data-testid={testId} className={cn('font-mono text-[2.143rem] font-bold', bad && 'text-bad')}>
        {children}
      </div>
    </Card>
  )
}

function SendError({ error, endpoint }: { error: Error; endpoint: string }) {
  if (isApiError(error) && error.status === 404) {
    return (
      <p data-testid="not-available" className="m-0 text-small text-muted">
        not available yet · {endpoint} → 404 {error.code}
      </p>
    )
  }
  return <RequestError title={`${endpoint} failed`} error={error} />
}

function Progress({ job, what }: { job: { status: string; progress: { completed: number; total: number } }; what: string }) {
  const { completed, total } = job.progress
  return (
    <div className="flex items-center gap-3 text-small" role="status">
      <progress value={completed} max={Math.max(total, 1)} aria-label={`${what} progress`} className="h-2 w-40 appearance-none overflow-hidden rounded-full [&::-webkit-progress-bar]:bg-panel [&::-webkit-progress-value]:bg-accent [&::-moz-progress-bar]:bg-accent" />
      <span className="font-mono">
        {job.status} · {completed} / {total}
      </span>
    </div>
  )
}

const MARK: Record<MarkTone, string> = {
  bad: 'bg-bad border-bad',
  held: 'bg-accent border-accent',
  good: 'bg-good border-good',
  // No plain grey boxes: an error is dotted ink, a variant not done yet is a dashed rule.
  error: 'border-[1.5px] border-dotted border-ink',
  pending: 'border-dashed border-rule',
}

function Marks({ tones, label }: { tones: MarkTone[]; label: string }) {
  return (
    <div role="img" aria-label={label} className="grid grid-cols-[repeat(20,minmax(0,1fr))] gap-[3px]">
      {tones.map((t, i) => (
        <span key={i} data-tone={t} className={cn('h-3.5 rounded-[2px] border', MARK[t])} />
      ))}
    </div>
  )
}

export function ProofPage() {
  const { evalJobId, redteamJobId, setEvalJob, setRedteamJob } = useProofStore()
  const evalQ = useJob<EvalJob>('eval', evalJobId, getEvalJob)
  const redQ = useJob<RedTeamJob>('redteam', redteamJobId, getRedTeamJob)
  const startEval = useMutation({
    mutationFn: () => createEvalJob({ suite: 'planted_errors_v1' }),
    onSuccess: (j) => setEvalJob(j.job_id),
  })
  // Raw text so the field can be edited freely; the contract allows 10 to 60.
  const [variantsText, setVariantsText] = useState('40')
  const variants = Number(variantsText)
  const variantsOk = Number.isInteger(variants) && variants >= 10 && variants <= 60
  const startRed = useMutation({
    mutationFn: () => createRedTeamJob({ variants }),
    onSuccess: (j) => setRedteamJob(j.job_id),
  })

  const ev = evalQ.data
  const rt = redQ.data
  const k = proofKpis(ev, rt)
  const rows = ev ? errorTypeRows(ev) : []
  const misses = ev?.items.filter((i) => !i.passed) ?? []
  const evalRunning = Boolean(ev && !jobDone(ev))
  const redRunning = Boolean(rt && !jobDone(rt))
  const dash = <span className="text-muted">—</span>

  return (
    <div className="flex flex-col font-prose">
      <div className="flex flex-wrap items-center gap-3.5 px-7 pt-5.5 pb-1.5">
        <h1 className="display m-0 text-[2rem]">How we know it works</h1>
        <span className="text-muted">
          {ev ? `${ev.items.length} invoices with planted errors and an answer key` : 'Invoices with planted errors and an answer key'}
          {rt ? `, plus attacks generated by ${rt.mutator_model}` : ', plus generated attacks'}
          {(ev?.execution ?? rt?.execution) === 'dry_run' && ' · dry-run bank: transfers recorded, not sent'}
        </span>
        <div className="ml-auto max-w-[27rem]">
          <SigSays expression="honest">My report card. I left the misses in, so you can check me.</SigSays>
        </div>
      </div>

      <div className="grid grid-cols-4 gap-3.5 px-7 py-3.5">
        <Tile label="Matches the answer key" testId="kpi-matches">
          {k.matches ? `${k.matches.value} / ${k.matches.of}` : dash}
        </Tile>
        <Tile label="Unauthorized payments" testId="kpi-unauthorized" bad={(k.unauthorized ?? 0) > 0}>
          {k.unauthorized ?? dash}
        </Tile>
        <Tile label="False holds on clean invoices" testId="kpi-false-holds" bad={(k.falseHolds?.value ?? 0) > 0}>
          {k.falseHolds ? `${k.falseHolds.value} / ${k.falseHolds.of}` : dash}
        </Tile>
        <Tile label="Unguarded agent fooled" testId="kpi-fooled" bad={Boolean(k.fooled)}>
          {k.fooled ? `${k.fooled.value} / ${k.fooled.of}` : dash}
        </Tile>
      </div>

      <div className="grid grid-cols-[minmax(0,1fr)_clamp(22rem,30vw,32.86rem)] items-start gap-[18px] px-7 pt-2 pb-7">
        <Card as="section" aria-label="Answer key results" className="flex flex-col gap-3 overflow-x-auto p-[18px]">
          <div className="flex flex-wrap items-center gap-3">
            <CardLabel>by planted error</CardLabel>
            <InkButton size="sm" className="ml-auto" onClick={() => startEval.mutate()} disabled={startEval.isPending || evalRunning}>
              {ev ? 'run the eval again' : 'run the answer-key eval'}
            </InkButton>
          </div>
          {startEval.isError && <SendError error={startEval.error} endpoint="POST /api/eval" />}
          {evalQ.isError && <SendError error={evalQ.error} endpoint={`GET /api/eval/${evalJobId}`} />}
          {ev && <Progress job={ev} what="Eval" />}
          {!ev ? (
            <p className="m-0 text-small text-muted">No eval run yet. The numbers above fill in from the job.</p>
          ) : (
            <table className="w-full border-collapse">
              <thead>
                <tr className="border-b-2 border-ink text-left text-muted">
                  <th className="px-1.5 py-2 font-medium">Planted error</th>
                  <th className="px-1.5 py-2 font-medium">Expected</th>
                  <th className="px-1.5 py-2 font-medium">Caught</th>
                  <th className="px-1.5 py-2 font-medium">Misses</th>
                </tr>
              </thead>
              <tbody>
                {rows.map((r) => (
                  <tr key={r.errorType} data-error-type={r.errorType} className="rule-dashed">
                    <td className="px-1.5 py-2">{r.label}</td>
                    <td className="px-1.5 py-2 font-mono">{r.expected}</td>
                    <td className={cn('px-1.5 py-2 font-mono', r.caught < r.total && 'text-bad')}>
                      {r.caught} / {r.total}
                    </td>
                    <td className="px-1.5 py-2">
                      {r.misses.length > 0 ? (
                        <a href={`#miss-${r.errorType}`} className="text-bad">
                          {r.misses.length} · view
                        </a>
                      ) : (
                        <span className="text-muted">none</span>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
          {ev && (
            <div>
              <CardLabel>misses</CardLabel>
              {misses.length === 0 ? (
                <p className="m-0 mt-1 text-small text-muted">None in this run{evalRunning ? ' so far' : ''}.</p>
              ) : (
                <ul aria-label="Misses" className="m-0 mt-1 list-none p-0 font-mono text-small">
                  {misses.map((m) => (
                    <li key={m.item_id} id={`miss-${m.error_type}`} className="text-bad">
                      {m.invoice_number} · {m.error_type} · expected {m.expected_outcome}
                      {m.expected_reason_code && ` (${m.expected_reason_code})`} · got {m.actual_outcome}
                      {m.actual_reason_codes.length > 0 && ` (${m.actual_reason_codes.join(', ')})`}
                    </li>
                  ))}
                </ul>
              )}
            </div>
          )}
          <div className="text-small text-muted">Misses are listed, not hidden.</div>
        </Card>

        <Card
          as="section"
          aria-label="Generated attacks"
          label={`generated attacks${rt ? ` · ${rt.mutator_model}` : ''}`}
          className="flex flex-col gap-3.5 p-[18px]"
        >
          {startRed.isError && <SendError error={startRed.error} endpoint="POST /api/redteam" />}
          {redQ.isError && <SendError error={redQ.error} endpoint={`GET /api/redteam/${redteamJobId}`} />}
          {rt ? (
            <>
              <Progress job={rt} what="Red team" />
              <div className="flex flex-col gap-1.5">
                <div className="text-meta text-muted">Unguarded agent, one mark per variant</div>
                <Marks tones={redteamMarks(rt).unguarded} label={`Unguarded: ${rt.metrics?.unguarded_compromised ?? '?'} paid the attacker`} />
                <div className="text-meta text-muted">Countersign, same variants</div>
                <Marks
                  tones={redteamMarks(rt).countersign}
                  label={`Countersign: ${rt.metrics?.countersign_held ?? '?'} held, ${rt.metrics?.countersign_unauthorized ?? '?'} unauthorized`}
                />
                <div className="text-meta text-muted">
                  Red: paid the attacker. Blue: held or blocked. Green: paid on file. Dotted: error. Dashed: not done yet.
                </div>
              </div>
              <div className="border-t border-dashed border-rule pt-3">
                <div className="text-meta text-muted">Distinct planner prompts across all variants</div>
                <div data-testid="distinct-prompts" className="font-mono text-[1.857rem] font-bold">
                  {rt.metrics?.distinct_planner_prompts ?? '—'}
                </div>
                <div className="text-small text-muted">If it&apos;s 1, the attack text never reached the part that decides.</div>
                {rt.metrics && (
                  <div className="mt-1 text-small">
                    Countersign: {rt.metrics.countersign_held} held · {rt.metrics.countersign_unauthorized} unauthorized ·{' '}
                    {rt.metrics.false_holds_on_controls} false holds on controls
                  </div>
                )}
              </div>
            </>
          ) : (
            <p className="m-0 text-small text-muted">No red-team run yet.</p>
          )}
          <div className="mt-auto flex flex-wrap items-center gap-2">
            <label className="flex items-center gap-1.5 text-small">
              variants
              <input
                type="number"
                min={10}
                max={60}
                value={variantsText}
                onChange={(e) => setVariantsText(e.target.value)}
                aria-invalid={!variantsOk}
                className={cn('ink-field w-[6ch] px-1.5 py-1 font-mono', !variantsOk && '!border-bad')}
              />
            </label>
            <InkButton onClick={() => startRed.mutate()} disabled={!variantsOk || startRed.isPending || redRunning}>
              {variantsOk ? `Run ${variants} new variants` : 'Run new variants'}
            </InkButton>
            {!variantsOk && <span className="text-small text-bad">10 to 60 variants</span>}
          </div>
        </Card>
      </div>
    </div>
  )
}
